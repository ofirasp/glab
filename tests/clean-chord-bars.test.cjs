const assert=require('node:assert/strict');require('../src/GuitarPracticeLab.Web/wwwroot/clean-chord-bars.js');
const base={time:.9,windowBar:0,windowStart:0,windowEnd:4.8,bar:2.4,pulse:.6,pulses:4,anchor:0,timeline:[{time:0,name:'G',sourceIndex:0},{time:2.4,name:'C',sourceIndex:1},{time:3.6,name:'D',sourceIndex:2}],matched:index=>index===0};
let bars=CleanChordBars.layout(base);
assert.deepEqual(bars.map(bar=>bar.segments.map(segment=>segment.name)),[['G'],['C','D']]);
